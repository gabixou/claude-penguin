import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const ctx = await b.newContext({ viewport: { width: 1024, height: 768 } });
const p = await ctx.newPage();
await p.goto('https://gopenguin.lol/?room=town', { waitUntil: 'domcontentloaded' });
await p.waitForFunction(() => window.penguinRoom?.movie, null, { timeout: 90000 });
await p.waitForTimeout(3000);
await p.mouse.move(100, 700);
await p.waitForTimeout(500);
await p.screenshot({ path: 'shots/gpD-town.png' });
console.log('cam', JSON.stringify(await p.evaluate(() => window.penguinCamera)));
await b.close();
