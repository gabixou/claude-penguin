import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const ctx = await b.newContext({ viewport: { width: 1024, height: 768 } });
const p = await ctx.newPage();
await p.goto('https://gopenguin.lol/?room=town', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(12000);
await p.mouse.move(150, 600);
await p.waitForTimeout(500);
await p.screenshot({ path: 'shots/gpB-t0.png' });
await p.waitForTimeout(2000);
await p.screenshot({ path: 'shots/gpB-t2.png' });
await p.waitForTimeout(2000);
await p.screenshot({ path: 'shots/gpB-t4.png' });
await b.close();
