import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const p = await b.newPage({ viewport: { width: 900, height: 600 } });
await p.goto('http://localhost:3000', { waitUntil: 'networkidle' });
await p.waitForFunction(() => window.__penguin?.scene?._movieReady, null, { timeout: 120000 });
await p.evaluate(() => window.__penguin.scene.toggleClothes());
await p.waitForTimeout(10000);
await p.evaluate(() => { window.__penguin.scene.wardrobe._gridCont.setMask(null); });
await p.waitForTimeout(500);
await p.screenshot({ path: 'tools/shots/wardrobe-nomask.png' });
await b.close();
