import { chromium } from 'playwright-core';
const [,, url, out, wait] = process.argv;
const browser = await chromium.launch({ executablePath: 'C:/Users/GABS/AppData/Local/ms-playwright/chromium-1208/chrome-win64/chrome.exe', args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 800, height: 520 } });
page.on('pageerror', e => console.log('PE:', String(e).slice(0,200)));
await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 30000 }).catch(()=>{});
await page.waitForTimeout(Number(wait||12000));
await page.screenshot({ path: out });
await browser.close();
console.log('saved', out);
