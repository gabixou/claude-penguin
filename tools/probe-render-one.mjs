import { chromium } from 'playwright-core';
import fs from 'node:fs';
const id = process.argv[2] || '38';
const scale = +(process.argv[3] || 6);
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const p = await (await b.newContext({ viewport: { width: 800, height: 600 } })).newPage();
await p.goto('http://localhost:3000/?penguin=Arenovisk', { waitUntil: 'domcontentloaded' });
await p.waitForFunction(() => window.__penguin?.scene?._movieReady === true, null, { timeout: 240000 });
await p.waitForTimeout(1500);
const url = await p.evaluate(async ({ id, scale }) => {
  const m = window.__penguin.scene.movie;
  const ch = m.characters[id];
  if (!ch?.file) return null;
  const svg = m._svgText(ch.file);
  const img = await new Promise((res) => { const i = new Image(); i.onload = () => res(i); i.onerror = () => res(null); i.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg); });
  if (!img) return 'NOIMG';
  const c = document.createElement('canvas');
  c.width = Math.ceil(img.width * scale) + 40; c.height = Math.ceil(img.height * scale) + 40;
  const ctx = c.getContext('2d');
  ctx.fillStyle = '#20304a'; ctx.fillRect(0, 0, c.width, c.height);
  ctx.drawImage(img, 20, 20, img.width * scale, img.height * scale);
  return c.toDataURL('image/png');
}, { id, scale });
if (url && url !== 'NOIMG') fs.writeFileSync(`shots/char-${id}-big.png`, Buffer.from(url.split(',')[1], 'base64'));
console.log('done', id, url === 'NOIMG' ? 'NOIMG' : 'ok');
await b.close();
