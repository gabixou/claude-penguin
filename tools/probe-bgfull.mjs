import { chromium } from 'playwright-core';
import fs from 'fs';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const p = await b.newPage({ viewport: { width: 1024, height: 768 } });
await p.goto('http://localhost:3000/?penguin=Arenovisk', { waitUntil: 'domcontentloaded' });
await p.waitForFunction(() => window.__penguin?.scene?._movieReady === true, null, { timeout: 120000 });
await p.waitForTimeout(1500);
const url = await p.evaluate(async () => {
  const sc = window.__penguin.scene, m = sc.movie;
  const ss = sc._ss;
  const main = m._mainTl.frames[0] || [];
  const bg = main.find(e => e.name === 'background_mc');
  if (!bg) return { err: 'no bg' };
  const c = document.createElement('canvas');
  c.width = Math.ceil(760 * ss); c.height = Math.ceil(480 * ss);
  await m.renderLayer(bg, c, ss);
  return c.toDataURL('image/png');
});
if (url.startsWith('data:')) fs.writeFileSync('shots/bg-full.png', Buffer.from(url.split(',')[1], 'base64'));
console.log('saved', url.length);
await b.close();
