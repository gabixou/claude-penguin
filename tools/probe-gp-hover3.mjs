import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const ctx = await b.newContext({ viewport: { width: 1024, height: 768 } });
const p = await ctx.newPage();
await p.goto('https://gopenguin.lol/?room=town', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(12000);
const info = await p.evaluate(() => {
  const c = document.querySelector('canvas');
  const r = c.getBoundingClientRect();
  return { x: r.x, y: r.y, w: r.width, h: r.height };
});
const scale = Math.min(info.w / 760, info.h / 480);
const ox = info.x + (info.w - 760 * scale) / 2;
const oy = info.y + (info.h - 480 * scale) / 2;
const sx = (wx) => ox + wx * scale;
const sy = (wy) => oy + wy * scale;
// hover NO CENTRO do botao: world ~(347,168)
await p.mouse.move(sx(600), sy(400));
await p.waitForTimeout(400);
await p.screenshot({ path: 'shots/gp3-idle.png' });
await p.mouse.move(sx(347), sy(168), { steps: 8 });
await p.waitForTimeout(400);
await p.screenshot({ path: 'shots/gp3-h1.png' });
await p.waitForTimeout(800);
await p.screenshot({ path: 'shots/gp3-h2.png' });
await p.waitForTimeout(1500);
await p.screenshot({ path: 'shots/gp3-h3.png' });
await p.mouse.move(sx(600), sy(400));
await p.waitForTimeout(500);
await p.screenshot({ path: 'shots/gp3-out.png' });
console.log('door screen pos', sx(347), sy(168));
await b.close();
